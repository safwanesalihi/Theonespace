// The public page's own dictionary (lib/i18n/public-dictionary.ts): of the English and Arabic dictionaries
// (lib/i18n/dictionaries.ts, every area of the app), only the words the landing can print, so a visitor
// in English or Arabic downloads a few kilobytes instead of the whole app's copy. The landing's files are
// those esbuild reaches from features/landing/landing.tsx; every string in them that is a French key of
// the dictionaries is kept, whether it goes through t() directly or through a list.
// node scripts/public-dictionary.mjs           writes the file
// node scripts/public-dictionary.mjs --check   fails if the file is not current (tests/public-home.mjs)
import { globSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const target = 'lib/i18n/public-dictionary.ts';

export async function build() {
  const esbuild = await import(pathToFileURL(globSync('node_modules/.pnpm/esbuild@*/node_modules/esbuild/lib/main.js')[0]));
  mkdirSync('.sites-runtime', { recursive: true });
  await esbuild.build({ stdin: { contents: "export { en, ar } from './lib/i18n/dictionaries';", resolveDir: process.cwd() }, outfile: '.sites-runtime/dictionaries.mjs', bundle: true, platform: 'node', format: 'esm', logLevel: 'error' });
  const { en, ar } = await import(`${pathToFileURL(process.cwd() + '/.sites-runtime/dictionaries.mjs')}?${Date.now()}`);
  // The landing's own files: everything it imports, outside node_modules.
  const graph = await esbuild.build({
    entryPoints: ['features/landing/landing.tsx'], bundle: true, write: false, metafile: true, platform: 'browser', format: 'esm', logLevel: 'error',
    packages: 'external', loader: { '.css': 'empty', '.svg': 'empty', '.png': 'empty', '.webp': 'empty' },
  });
  // The dictionaries themselves hold every key: they are what we pick from, not words the page prints.
  const files = Object.keys(graph.metafile.inputs).filter((f) => !f.includes('node_modules') && !f.startsWith('lib/i18n/') && /\.(ts|tsx)$/.test(f)).sort();
  if (process.env.LIST) console.log(files.join('\n'));
  const keys = new Set();
  for (const file of files) {
    const src = readFileSync(file, 'utf8');
    for (const m of src.matchAll(/(["'`])((?:\\.|(?!\1)[^\\\n])+)\1/g)) {
      const text = m[2].replace(/\\(.)/g, '$1');
      if (m[1] === '`' && text.includes('${')) continue;
      if (text in en) keys.add(text);
    }
  }
  const pick = (dict) => Object.fromEntries([...keys].sort().map((k) => [k, dict[k]]));
  const body = (name, dict) => `export const ${name}: Record<string, string> = ${JSON.stringify(pick(dict), null, 2)};\n`;
  return `// Generated by scripts/public-dictionary.mjs from lib/i18n/dictionaries.ts: the words the public page\n// (features/landing) can print, in English and Arabic. Do not edit; run the script again.\n// ${keys.size} keys, from ${files.length} files.\n${body('en', en)}${body('ar', ar)}`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = await build();
  if (process.argv.includes('--check')) {
    let now = ''; try { now = readFileSync(target, 'utf8'); } catch { /* missing */ }
    if (now.replace(/\r\n/g, '\n') !== out) { console.error(`${target} is not current: node scripts/public-dictionary.mjs`); process.exit(1); }
    console.log(`${target} is current`);
  } else { writeFileSync(target, out); console.log(`wrote ${target}`); }
}

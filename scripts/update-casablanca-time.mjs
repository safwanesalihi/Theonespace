// Refresh with a Node.js runtime whose IANA timezone database is current.
// Source: https://data.iana.org/time-zones/tzdb/africa (public-domain Morocco rules).
// Keep one small zone table so older WebKit/Chromium timezone data cannot drift.
import { writeFileSync } from 'node:fs';
// Morocco moved to UTC+0 for good on 2026-09-20 (tzdb 2026c). An older runtime would write the old +01 rules back.
if (process.versions.tz < '2026c') throw Error(`This Node.js has tzdata ${process.versions.tz}; use one with 2026c or newer.`);
const start = Date.UTC(2018, 0, 1), end = Date.UTC(2041, 0, 1);
const format = new Intl.DateTimeFormat('en-GB', { timeZone: 'Africa/Casablanca', timeZoneName: 'longOffset' });
const offset = ms => {
  const label = format.formatToParts(new Date(ms)).find(p => p.type === 'timeZoneName').value;
  if (label === 'GMT') return 0;
  const match = /^GMT([+-])(\d{2}):(\d{2})$/.exec(label);
  if (!match) throw Error(`Unexpected offset: ${label}`);
  return (match[1] === '-' ? -1 : 1) * (Number(match[2]) * 60 + Number(match[3])) * 60;
};
const transitions = [[start / 1000, offset(start)]];
for (let at = start + 12 * 3600_000; at <= end; at += 12 * 3600_000) {
  if (offset(at) === transitions.at(-1)[1]) continue;
  let low = at - 12 * 3600_000, high = at;
  while (high - low > 1000) { const mid = Math.floor((low + high) / 2000) * 1000; if (offset(mid) === offset(low)) low = mid; else high = mid; }
  transitions.push([high / 1000, offset(high)]);
}
const data = `// IANA Africa/Casablanca, tzdb ${process.versions.tz}. Generated by scripts/update-casablanca-time.mjs.\n// Source: https://data.iana.org/time-zones/tzdb/africa (public domain).\n// UTC transition seconds and offset seconds. Morocco has been on UTC+0 without Ramadan changes since 2026-09-20.\nexport const casablancaRange = [${start / 1000}, ${end / 1000}] as const;\nexport const casablancaTransitions: readonly (readonly [number, number])[] = [\n${transitions.map(row => `  [${row.join(', ')}],`).join('\n')}\n];\n`;
writeFileSync('lib/casablanca-offsets.ts', data);
console.log(`Generated ${transitions.length} Casablanca transitions from IANA ${process.versions.tz}.`);
